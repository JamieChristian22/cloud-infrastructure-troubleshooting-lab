"""Deterministic, offline incident replay with machine-readable evidence."""
import json
import secrets
import threading
import time
from datetime import datetime, timezone
from pathlib import Path

from .client import request
from .server import build_server

SCENARIOS = [
    ('dependency_outage', 503, 503, 'Check dependency readiness and upstream connectivity'),
    ('high_latency', 200, 200, 'Check request durations and upstream response time'),
    ('application_error', 200, 500, 'Correlate request ID with application error logs'),
    ('auth_misconfig', 200, 401, 'Validate upstream service identity and credential configuration'),
]


def run_replay(output: Path) -> dict:
    server = build_server(token=secrets.token_urlsafe(24))
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    url = f'http://127.0.0.1:{server.server_port}'
    results = []
    try:
        baseline_ready, _ = request(url, '/health/ready')
        baseline_api, _ = request(url, '/api/orders')
        if (baseline_ready, baseline_api) != (200, 200):
            raise AssertionError('Baseline service failed')
        for fault, expected_ready, expected_api, next_step in SCENARIOS:
            status, _ = request(url, '/ops/fault', token=server.lab_token, body={'fault': fault})  # type: ignore[attr-defined]
            if status != 200:
                raise AssertionError(f'Unable to inject {fault}')
            ready, _ = request(url, '/health/ready')
            start = time.monotonic()
            api, response = request(url, '/api/orders')
            api_ms = round((time.monotonic() - start) * 1000, 2)
            passed = ready == expected_ready and api == expected_api
            results.append({'scenario': fault, 'expected_readiness_http': expected_ready,
                            'observed_readiness_http': ready, 'expected_api_http': expected_api,
                            'observed_api_http': api, 'observed_api_latency_ms': api_ms,
                            'investigation_next_step': next_step, 'result': 'PASS' if passed else 'FAIL',
                            'api_response': response})
            status, _ = request(url, '/ops/fault', token=server.lab_token, body={'fault': 'none'})  # type: ignore[attr-defined]
            restored, _ = request(url, '/api/orders')
            results[-1]['recovery_http'] = restored
            results[-1]['recovery_verified'] = status == 200 and restored == 200
        report = {'lab': 'Cloud Infrastructure Troubleshooting Lab',
                  'execution_mode': 'local simulation; synthetic data; no cloud resources',
                  'generated_at_utc': datetime.now(timezone.utc).isoformat(),
                  'baseline': {'readiness_http': baseline_ready, 'api_http': baseline_api},
                  'scenarios': results, 'total_scenarios': len(results),
                  'successful_scenarios': sum(r['result'] == 'PASS' and r['recovery_verified'] for r in results),
                  'complete': all(r['result'] == 'PASS' and r['recovery_verified'] for r in results)}
        output.mkdir(parents=True, exist_ok=True)
        (output / 'incident-replay.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
        lines = ['# Executed incident replay — synthetic local environment', '',
                 f"Run (UTC): {report['generated_at_utc']}", '',
                 'This artifact was generated by a **real local test run** against a deliberately fault-injected',
                 'Python HTTP service. It is not evidence of a production incident or AWS deployment.', '',
                 '| Fault | Expected ready | Observed ready | Expected API | Observed API | Recovery | Result |',
                 '| --- | ---: | ---: | ---: | ---: | ---: | ---: |']
        for item in results:
            lines.append(f"| {item['scenario']} | {item['expected_readiness_http']} | {item['observed_readiness_http']} | {item['expected_api_http']} | {item['observed_api_http']} | {item['recovery_http']} | {item['result']} |")
        lines.extend(['', f"**All scenarios passed and recovered:** {'yes' if report['complete'] else 'no'}", '',
                      'Reproduce locally with `python -m cloudops_lab demo --output evidence`.', ''])
        (output / 'incident-replay.md').write_text('\n'.join(lines), encoding='utf-8')
        return report
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=3)
